"""CPU toy: power and calibration of the scale/shift-fitted statistic. Writes docs/toy-results.md.

Usage: python scripts/toy_power.py [--g 20] [--n0 200] [--n1 80] [--seed 0] [--workers 4]
"""
from __future__ import annotations

import argparse
import json
import sys
import time
from multiprocessing import Pool
from pathlib import Path

import numpy as np
from scipy.linalg import solve_triangular
from scipy.stats import chi2

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
from dcal.stat import _whiten, align_samples, empirical_threshold, fault_statistic  # noqa: E402
from dcal.toy import ToyConfig, World  # noqa: E402

VARIANTS = ["known", "oracle", "kernel", "kernel_nr", "shrunk"]
G = {}


def init(g, seed):
    G["w"] = World(ToyConfig(g=g), seed)


def one(args):
    fault, kappa, area, seed = args
    w = G["w"]
    rng = np.random.default_rng(seed)
    S, D, Kr, Ku, (a, b) = w.simulate(rng, fault, kappa, area)
    out = {}
    A = align_samples(S)
    m = A.mean(0)
    Sp = (1 + 1 / w.cfg.M) * Ku
    L = _whiten(a * a * Sp + Kr)                       # oracle covariance AND true (a, b): unattainable bound
    e = solve_triangular(L, a * m + b - D, lower=True)
    out["known"] = float(e @ e)
    out["oracle"] = fault_statistic(S, D, Kr, Sigma_u=Ku, robust=True)["T"]
    out["kernel"] = fault_statistic(S, D, Kr, grid_shape=w.shape, cov="kernel", robust=True)["T"]
    out["kernel_nr"] = fault_statistic(S, D, Kr, grid_shape=w.shape, cov="kernel", robust=False)["T"]
    out["shrunk"] = fault_statistic(S, D, Kr, grid_shape=w.shape, cov="shrunk", robust=True)["T"]
    return out


def run(pool, fault, kappa, area, n, base):
    jobs = [(fault, kappa, area, base + i) for i in range(n)]
    res = pool.map(one, jobs, chunksize=4)
    return {v: np.array([r[v] for r in res]) for v in VARIANTS}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--g", type=int, default=20)
    ap.add_argument("--n0", type=int, default=200)
    ap.add_argument("--n1", type=int, default=80)
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--workers", type=int, default=4)
    ap.add_argument("--out", default=str(Path(__file__).resolve().parents[1] / "docs" / "toy-results.md"))
    args = ap.parse_args()
    t0 = time.time()
    n = args.g ** 2
    kappas = [0.5, 1.0, 1.5, 2.5, 4.0]
    with Pool(args.workers, initializer=init, initargs=(args.g, args.seed)) as pool:
        null = run(pool, None, 0.0, 0.0, args.n0, 10_000 + args.seed)
        thr = {v: empirical_threshold(null[v], 0.05) for v in VARIANTS}
        chi_thr = chi2.ppf(0.95, n - 2)
        res = {"null": {v: {"mean_T": float(null[v].mean()), "mean_T_over_dof": float(null[v].mean() / (n - 2)),
                            "far_at_chi2": float((null[v] > chi_thr).mean()), "emp_thr": thr[v]} for v in VARIANTS}}
        power = {}
        for fault in ["square", "warp", "edge"]:
            power[fault] = {}
            for k in kappas:
                r = run(pool, fault, k, 0.12, args.n1, 20_000 + args.seed)
                power[fault][k] = {v: float((r[v] > thr[v]).mean()) for v in VARIANTS}
        res["power"] = power
        for kind in ["shift", "affine"]:
            r = run(pool, kind, 8.0, 0.0, args.n1, 30_000 + args.seed)
            res[f"{kind}_kappa8"] = {v: float((r[v] > thr[v]).mean()) for v in VARIANTS}
        sweep = {}
        for area in [0.05, 0.15, 0.30, 0.45, 0.60]:
            r = run(pool, "square", 2.5, area, args.n1, 40_000 + args.seed)
            sweep[area] = {v: float((r[v] > thr[v]).mean()) for v in VARIANTS}
        res["area_sweep_kappa2.5"] = sweep
    res["meta"] = {"g": args.g, "n": n, "M": ToyConfig().M, "n0": args.n0, "n1": args.n1, "seconds": time.time() - t0,
                   "chi2_thr95": float(chi_thr)}

    def mdf(curve):
        ks = sorted(curve)
        p = [curve[k] for k in ks]
        for i in range(len(ks)):
            if p[i] >= 0.8:
                if i == 0:
                    return f"<={ks[0]}"
                k0, k1, p0, p1 = ks[i - 1], ks[i], p[i - 1], p[i]
                return f"{k0 + (0.8 - p0) * (k1 - k0) / max(p1 - p0, 1e-9):.2f}"
        return f">{ks[-1]}"

    L = []
    L.append("# Toy results: scale/shift-fitted statistic (CPU, synthetic Gaussian toy)\n")
    L.append(f"Generated by `scripts/toy_power.py`; grid {args.g}x{args.g} (n={n}), M={ToyConfig().M} samples, "
             f"{args.n0} clean trials for the null, {args.n1} per fault cell, alpha=0.05, {res['meta']['seconds']:.0f} s.")
    L.append("Variants: `known` = oracle covariance and TRUE (a,b), no fit (unattainable bound); `oracle` = oracle covariance, "
             "(s,t) fitted robustly; `kernel` = stationary-kernel covariance estimated from the M samples, robust fit; "
             "`kernel_nr` = same, non-robust fit; `shrunk` = rank-(M-1) sample covariance shrunk to its diagonal, robust fit.")
    L.append("Faults are in units of the per-pixel total residual sd, applied to the samples (the measurement), 12% area "
             "for square/edge. Threshold = empirical 95% quantile of the clean-view null of the *same pipeline* "
             "(so the two-parameter fit is inside the null).\n")
    L.append("## Null calibration\n")
    L.append(f"| variant | mean T | mean T/(n-2) | false-alarm at chi2(n-2) 95% ({chi_thr:.0f}) |\n|---|---|---|---|")
    for v in VARIANTS:
        d = res["null"][v]
        L.append(f"| {v} | {d['mean_T']:.1f} | {d['mean_T_over_dof']:.2f} | {d['far_at_chi2']:.2f} |")
    L.append("\n## Power vs fault magnitude (kappa), and minimum detectable fault at 80% power\n")
    for fault in power:
        L.append(f"**{fault}**\n")
        L.append("| kappa | " + " | ".join(VARIANTS) + " |\n|---|" + "---|" * len(VARIANTS))
        for k in kappas:
            L.append(f"| {k} | " + " | ".join(f"{power[fault][k][v]:.2f}" for v in VARIANTS) + " |")
        L.append("| **MDF (kappa)** | " + " | ".join(mdf({k: power[fault][k][v] for k in kappas}) for v in VARIANTS) + " |\n")
    L.append("## Global faults, kappa=8 (power)\n")
    L.append("`shift` = constant offset (absorbed exactly by t). `affine` = fault proportional to the truth relief "
             "(a scale change; not blind, because the fitted scale also rescales the sample covariance s^2 Sigma_U).\n")
    L.append("| fault | " + " | ".join(VARIANTS) + " |\n|---|" + "---|" * len(VARIANTS))
    for kind in ["shift", "affine"]:
        L.append(f"| {kind} | " + " | ".join(f"{res[kind + '_kappa8'][v]:.2f}" for v in VARIANTS) + " |")
    L.append("")
    L.append("## Square fault, kappa=2.5, power vs area fraction (robust vs non-robust fit)\n")
    L.append("| area | " + " | ".join(VARIANTS) + " |\n|---|" + "---|" * len(VARIANTS))
    for a, d in sweep.items():
        L.append(f"| {a} | " + " | ".join(f"{d[v]:.2f}" for v in VARIANTS) + " |")
    Path(args.out).write_text("\n".join(L) + "\n")
    Path(args.out).with_suffix(".json").write_text(json.dumps(res, indent=1, default=float))
    print("\n".join(L))


if __name__ == "__main__":
    main()
