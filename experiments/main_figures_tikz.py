# ------------------------------------------------------------------------------------------ U P U^T


def upu() -> str:
    """Analytic illustration: 30 pixels on 3 surfels (12, 10, 8 pixels), surfel 1 weakly supported."""
    sizes, pvar = [12, 10, 8], [(1.0, 0.3), (0.04, 0.01), (0.04, 0.01)]  # (offset, tilt) variances [sigma^2]
    n = sum(sizes)
    U = np.zeros((n, 2 * len(sizes)))
    P = np.zeros((2 * len(sizes),) * 2)
    r0 = 0
    for k, (m, (po, pt)) in enumerate(zip(sizes, pvar)):
        s = np.linspace(-1, 1, m)
        U[r0:r0 + m, 2 * k] = 1.0
        U[r0:r0 + m, 2 * k + 1] = s
        P[2 * k, 2 * k], P[2 * k + 1, 2 * k + 1] = po, pt
        r0 += m
    S_full = np.eye(n) + U @ P @ U.T  # sensor noise (unit, independent here) + surface term
    S_diag = np.diag(np.diag(S_full))
    rng = np.random.default_rng(7)
    L = np.linalg.cholesky(S_full)
    draws = [L @ rng.normal(size=n) for _ in range(3)]
    sty = ["sfred", "black", "sforange"]
    samp = "\n".join(rf"\addplot[{c}, line width=0.7pt, mark=*, mark size=0.6pt] coordinates {{{' '.join(f'({u},{v:.3f})' for u, v in enumerate(d))}}};"
                     for c, d in zip(sty, draws))
    vmax = float(S_full.max())

    def mat(S):
        return " ".join(f"({c},{r}) [{S[r, c]:.3f}]" for r in range(n) for c in range(n))

    w = np.arange(1, sizes[0] + 1)
    ratio = [(np.ones(k) @ S_full[:k, :k] @ np.ones(k)) / np.trace(S_full[:k, :k]) for k in w]
    rat = " ".join(f"({k},{v:.3f})" for k, v in zip(w, ratio))
    bounds = np.cumsum(sizes)[:-1] - 0.5
    vlines = "\n".join(rf"\draw[sfgrey, densely dotted, line width=0.5pt] (axis cs:{b},-4.5) -- (axis cs:{b},4.5);" for b in bounds)
    blines = lambda: "\n".join(  # noqa: E731
        rf"\draw[white, line width=0.5pt] (axis cs:{b},-0.5) -- (axis cs:{b},{n - 0.5}); \draw[white, line width=0.5pt] (axis cs:-0.5,{b}) -- (axis cs:{n - 0.5},{b});"
        for b in bounds)
    mopts = (rf"width=2.2cm, height=2.2cm, xmin=-0.5, xmax={n - 0.5}, ymin=-0.5, ymax={n - 0.5}, y dir=reverse, axis equal image, "
             rf"enlargelimits=false, axis on top, xtick={{0,10,20}}, ytick={{0,10,20}}, point meta min=0, point meta max={vmax:.2f}, "
             rf"xlabel={{Pixel}}, ylabel={{Pixel}}")
    return rf"""% Why U P U^T matters: analytic example (generated by experiments/main_figures_tikz.py)
\begin{{tikzpicture}}
\begin{{groupplot}}[sfaxis, group style={{group size=4 by 1, horizontal sep=1.05cm}}, scale only axis]
\nextgroupplot[width=2.4cm, height=2.2cm, title={{\sfsub{{a}}}}, xmin=-0.5, xmax={n - 0.5}, ymin=-4.5, ymax=4.5, xlabel={{Pixel}},
  ylabel={{Residual [$\sigma$]}}, xtick={{0,10,20}}]
\fill[sfred, opacity=0.07] (axis cs:-0.5,-4.5) rectangle (axis cs:{bounds[0]},4.5);
{vlines}
{samp}
\node[font=\sffamily\fontsize{{5.5}}{{6}}\selectfont, text=sfred, anchor=north] at (axis cs:5.5,4.3) {{weak surfel}};
\nextgroupplot[{mopts}, title={{\sfsub{{b}} full $UPU^{{\top}}$}}, ylabel={{}}]
\addplot[matrix plot*, point meta=explicit, mesh/cols={n}] coordinates {{{mat(S_full)}}};
{blines()}
\nextgroupplot[{mopts}, title={{\sfsub{{c}} diagonal only}}, ylabel={{}}, yticklabels={{}}]
\addplot[matrix plot*, point meta=explicit, mesh/cols={n}] coordinates {{{mat(S_diag)}}};
{blines()}
\nextgroupplot[width=1.95cm, height=2.2cm, title={{\sfsub{{d}}}}, xmin=0, xmax={sizes[0] + 1}, ymin=0, xlabel={{Region width [px]}},
  ylabel={{Ratio full/diag.}}, xtick={{1,4,8,12}}]
\addplot[sfred, line width=0.9pt, mark=x, mark size=1.8pt] coordinates {{{rat}}};
\addplot[black, dashed, line width=0.6pt, domain=0:{sizes[0] + 1}, samples=2] {{1}};
\end{{groupplot}}
\begin{{axis}}[sfcolorbar=5.45cm, at={{($(group c2r1.south west)+(0,-0.95cm)$)}}, anchor=north west, point meta min=0,
  point meta max={vmax:.2f}, colorbar style={{xlabel={{Covariance of residuals [$\sigma^2$]}}}}]
\addplot[draw=none] coordinates {{(0,0)}};
\end{{axis}}
\end{{tikzpicture}}
""", ratio[-1]


