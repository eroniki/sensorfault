def compile_check(ms: Path, names: list[str], out: Path) -> None:
    """Standalone PDFs (and PNG previews) of each figure, compiled from the manuscript root."""
    style = (ms / "figures" / "figstyle.tex").read_text()
    out.mkdir(parents=True, exist_ok=True)
    for n in names:
        wrap = out / f"{n}_check.tex"
        wrap.write_text(
            "\\documentclass[12pt,border=4pt]{standalone}\n\\usepackage{pgfplots}\n\\usepgfplotslibrary{groupplots}\n"
            + LIBS + "\n\\usepackage{sansmath}\n\\usepackage{graphicx}\n\\pgfplotsset{compat=1.16}\n" + style
            + "\n\\newcommand{\\efigdir}{figures/e1}\\newcommand{\\qfigdir}{figures/e1q}\\newcommand{\\rfigdir}{figures/rgb}"
            "\\newcommand{\\mfigdir}{figures/main}\n\\begin{document}\n\\input{figures/main/" + n + ".tex}\n\\end{document}\n")
        r = subprocess.run(["pdflatex", "-interaction=nonstopmode", "-halt-on-error", f"-output-directory={out}", str(wrap)],
                           cwd=ms, capture_output=True, text=True)
        if r.returncode != 0:
            raise RuntimeError(n + ": " + "\n".join(x for x in r.stdout.splitlines() if x.startswith("!") or "Error" in x)[:900])
        pdf = out / f"{n}_check.pdf"
        size = subprocess.run(["pdfinfo", str(pdf)], capture_output=True, text=True).stdout
        pts = [line for line in size.splitlines() if line.startswith("Page size")][0]
        wpt = float(pts.split()[2])
        print(f"{n}: {wpt:.0f} pt wide incl. 8 pt border (text width 390 pt)")
        subprocess.run(["pdftoppm", "-png", "-r", "150", "-singlefile", str(pdf), str(out / f"{n}_preview")], check=True)
        for ext in ("aux", "log", "tex"):
            (out / f"{n}_check.{ext}").unlink(missing_ok=True)


def main(manuscript: str) -> None:
    ms = Path(manuscript).resolve()
    d = ms / "figures" / "main"
    d.mkdir(parents=True, exist_ok=True)
    meta = json.loads((ROOT / "results/e1/qualitative/meta.json").read_text())
    m = json.loads((ROOT / "results/rgb/metrics.json").read_text())
    # median test view for the compact RGB panel (rendered by rgb_render_view.py)
    psnrs = sorted((v["psnr"], v["frame"]) for v in m["test"]["per_view"])
    frame = psnrs[len(psnrs) // 2][1]
    from PIL import Image

    sys.path.insert(0, str(HERE))
    from rgb_figures import err_png

    rgb = ROOT / "results/rgb"
    err_png(rgb / f"test_{frame:04d}_render.png", rgb / f"test_{frame:04d}_gt.png", rgb / f"test_{frame:04d}_err.png")
    for k in ("gt", "render", "err"):
        Image.open(rgb / f"test_{frame:04d}_{k}.png").resize((480, 270), Image.LANCZOS).save(ms / "figures/rgb" / f"test_{frame:04d}_{k}.png", optimize=True)
    upu_tex, ratio = upu()
    figs = {"fig_overview": overview(), "fig_aerial": aerial(), "fig_upu": upu_tex, "fig_e1_compact": e1_compact(meta),
            "fig_rgb_compact": rgb_compact(frame, m)}
    for n, t in figs.items():
        (d / f"{n}.tex").write_text(t)
    (d / "facts.json").write_text(json.dumps({"rgb_frame": frame, "upu_full_region_ratio": round(ratio, 2)}, indent=1))
    if shutil.which("pdflatex"):
        compile_check(ms, list(figs), ROOT / "results" / "main_figures")
    print(json.dumps({"rgb_frame": frame, "upu_full_region_ratio": round(ratio, 2)}))


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else str(ROOT.parent / "sensorfault-manuscript"))
