def e1_compact(meta: dict) -> str:
    V, sc = meta["views"], meta["scales"]
    rows = ["clean", "faulty", "swamped"]
    lab = {"clean": "Clean", "faulty": "Faulty", "swamped": "Swamped\\\\neighbour"}
    labels = [f"{lab[t]}\\\\view {V[t]['view']}" for t in rows]
    titles = ["True depth", "Cavity render", "Standardised", "Region scan $|z|$"]
    cbs = [
        ("sfviridis", f"{sc['depth_m'][0]:.0f}", f"{sc['depth_m'][1]:.0f}", "Depth [m]"),
        ("sfviridis", f"{sc['depth_m'][0]:.0f}", f"{sc['depth_m'][1]:.0f}", "Depth [m]"),
        ("sfrdbu", "-5", "5", "Residual [$\\sigma$]"),
        ("sfviridis", "0", "20", "$|z|$ per tile ($\\geq$20 clipped)"),
    ]
    return "% E1 per-view test, compact (generated by experiments/main_figures_tikz.py)\n" + image_grid(
        rows, ["gt", "render", "std", "scan"], cbs, labels, titles, w=2.95, h=2.95 * 54 / 96)


