def bspline(ctrl: np.ndarray, t: np.ndarray) -> np.ndarray:
    """Uniform cubic B-spline through control values ctrl at knots 0..n-1; t in [1, n-2)."""
    i = np.clip(np.floor(t).astype(int), 1, len(ctrl) - 3)
    s = t - i
    b = np.stack([(1 - s) ** 3, 3 * s**3 - 6 * s**2 + 4, -3 * s**3 + 3 * s**2 + 3 * s + 1, s**3], -1) / 6
    return sum(b[:, k] * ctrl[i - 1 + k] for k in range(4))


