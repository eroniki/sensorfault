def extent(cell: float, S: dict) -> tuple[float, float, float, float]:
    x0, x1, y0, y1 = S["extent_m"]
    nx, ny = int(np.ceil((x1 - x0) / cell)), int(np.ceil((y1 - y0) / cell))
    return x0, x0 + nx * cell, y0, y0 + ny * cell


def hull(pts: np.ndarray) -> np.ndarray:
    """Convex hull (monotone chain) of 2D points, closed."""
    p = sorted(map(tuple, pts))

    def half(seq):
        h = []
        for q in seq:
            while (
                len(h) >= 2
                and (h[-1][0] - h[-2][0]) * (q[1] - h[-2][1])
                - (h[-1][1] - h[-2][1]) * (q[0] - h[-2][0])
                <= 0
            ):
                h.pop()
            h.append(q)
        return h

    lo, up = half(p), half(p[::-1])
    h = lo[:-1] + up[:-1]
    return np.array(h + [h[0]])


def fault_outline(S: dict) -> str:
    pts = np.loadtxt(SRC / "fault_cells.csv", delimiter=",", skiprows=1)
    h = hull(pts)
    return " ".join(f"({x:.1f},{y:.1f})" for x, y in h)


def map_axis(img: str, ext, opts: str = "", overlay: str = "") -> str:
    x0, x1, y0, y1 = ext
    return (
        rf"\nextgroupplot[{opts}]"
        + "\n"
        + rf"\addplot graphics[xmin={x0}, xmax={x1}, ymin={y0}, ymax={y1}] {{\sfigdir/{img}}};"
        + ("\n" + overlay if overlay else "")
    )


def colorbar(at: str, cmap: str, lo, hi, label: str, width: float, extra: str = "") -> str:
    return rf"""\begin{{axis}}[sfcolorbar={width}cm, colormap name={cmap}, at={{{at}}}, anchor=north, point meta min={lo}, point meta max={hi},
  colorbar style={{xlabel={{{label}}}{extra}}}]
\addplot[draw=none] coordinates {{(0,0)}};
\end{{axis}}"""


GROUP = (
    r"\begin{{groupplot}}[sfaxis, group style={{group size={nc} by {nr}, horizontal sep={hs}cm, vertical sep={vs}cm}}, "
    r"scale only axis, width={w}cm, height={h:.3f}cm, enlargelimits=false, axis on top, xmin={x0}, xmax={x1}, ymin={y0}, ymax={y1}, "
    r"xtick={{-300,0,300}}, ytick={{-800,-600,-400}}, title style={{font=\sffamily\scriptsize, yshift=-2pt}}, "
    r"xlabel={{X [m]}}, ylabel={{Y [m]}}, ylabel style={{yshift=-4pt}}]"
)


def group(nc, nr, w, ext, hs=0.25, vs=0.9):
    x0, x1, y0, y1 = ext
    h = w * (y1 - y0) / (x1 - x0)
    return GROUP.format(nc=nc, nr=nr, hs=hs, vs=vs, w=w, h=h, x0=x0, x1=x1, y0=y0, y1=y1), h


def fmt(v, nd=2):
    return f"${v:+.{nd}f}$" if v is not None else "--"


def compact(S) -> str:
    e2, e4 = extent(S["cell_m"]["gt_rgb2dgs"], S), extent(S["cell_m"]["e1"], S)
    zlo, zhi = S["scales"]["height_m"]
    rm = S["scales"]["residual_m"]
    ol = rf"\addplot[black, line width=0.6pt, dashed] coordinates {{{fault_outline(S)}}};"
    w = 2.72
    g, h = group(4, 1, w, e2, hs=0.18)
    noy = "ylabel={}, yticklabels={}"
    # (c, d) zoom onto the injected fault, same aspect as the panels; window marked in (a)
    zx0, zx1 = 170.0, 402.0
    zh = (zx1 - zx0) * (e2[3] - e2[2]) / (e2[1] - e2[0])
    zy0 = -712.0
    zy1 = zy0 + zh
    zoom = (
        rf"xmin={zx0}, xmax={zx1}, ymin={zy0}, ymax={zy1:.1f}, xtick={{200,300,400}}, ytick={{-700,-600}}, "
        r"yticklabels={}, ylabel={}"
    )
    box = rf"\draw[black, line width=0.6pt] (axis cs:{zx0},{zy0}) rectangle (axis cs:{zx1},{zy1:.1f});"
    body = "\n".join(
        [
            map_axis("dsm_gt.png", e2, r"title={\sfsub{a} Ground truth}", box),
            map_axis("res_rgb2dgs.png", e2, r"title={\sfsub{b} RGB 2DGS $-$ GT}, " + noy),
            map_axis("res_e1_off.png", e4, r"title={\sfsub{c} E1, gate off}, " + zoom, ol),
            map_axis("res_e1_on.png", e4, r"title={\sfsub{d} E1, gate on}, " + zoom, ol),
        ]
    )
    return (
        "% Surface comparison, compact (generated by experiments/surface_figures_tikz.py)\n\\begin{tikzpicture}\n"
        + g
        + "\n"
        + body
        + "\n\\end{groupplot}\n"
        + colorbar(
            r"($(group c1r1.south)+(0,-0.85cm)$)",
            "sfviridis",
            f"{zlo:.0f}",
            f"{zhi:.0f}",
            "Height [m]",
            w,
        )
        + "\n"
        + colorbar(
            r"($(group c2r1.south)!0.5!(group c4r1.south)+(0,-0.85cm)$)",
            "sfrdbu",
            -rm,
            rm,
            rf"Reconstruction $-$ GT height [m] ($\pm${rm:.0f} clipped)",
            2 * w + 0.36,
        )
        + "\n\\end{tikzpicture}\n"
    )


