def table(S) -> str:
    rows = []

    def row(label, st):
        if not st or st.get("n_cells", 0) == 0:
            return
        rows.append(
            rf"{label} & {st['n_cells']} & {fmt(st['median_m'])} & {st['rmse_m']:.2f} & {fmt(st['p05_m'])} & {fmt(st['p95_m'])} & "
            rf"{st['abs_p90_m']:.2f} & {100 * st['within_1m']:.0f} \\"
        )

    A, Lnd, Wt, F = (
        S["residual_all"],
        S["residual_land"],
        S["residual_water"],
        S["residual_fault_region"],
    )
    rows.append(r"\multicolumn{8}{l}{\emph{RGB 2DGS, 2~m cells}} \\")
    row("All cells", A["rgb2dgs"])
    row("Land", Lnd["rgb2dgs"])
    row("Water", Wt["rgb2dgs"])
    rows.append(r"\midrule")
    rows.append(r"\multicolumn{8}{l}{\emph{E1 surfels, 4~m cells, all cells}} \\")
    row("No fault (reference)", A["e1_ref"])
    row("Fault, gate off", A["e1_off"])
    row("Fault, gate on", A["e1_on"])
    rows.append(r"\midrule")
    rows.append(r"\multicolumn{8}{l}{\emph{E1 surfels, cells under the injected fault}} \\")
    row("No fault (reference)", F["e1_ref"])
    row("Fault, gate off", F["e1_off"])
    row("Fault, gate on", F["e1_on"])
    return (
        "% generated by experiments/surface_figures_tikz.py\n\\begin{tabular}{lrrrrrrr}\n\\toprule\n"
        "Surface & Cells & Median & RMSE & P5 & P95 & $|r|$ P90 & $\\le$1~m \\\\\n"
        " & & [m] & [m] & [m] & [m] & [m] & [\\%] \\\\\n\\midrule\n"
        + "\n".join(rows)
        + "\n\\bottomrule\n\\end{tabular}\n"
    )


def compile_check(ms: Path, names: list[str], out: Path) -> None:
    style = (ms / "figures" / "figstyle.tex").read_text()
    out.mkdir(parents=True, exist_ok=True)
    for n in names:
        wrap = out / f"{n}_check.tex"
        wrap.write_text(
            "\\documentclass[12pt,border=4pt]{standalone}\n\\usepackage{pgfplots}\n\\usepgfplotslibrary{groupplots}\n"
            "\\usetikzlibrary{calc,arrows.meta,positioning}\n\\usepackage{sansmath}\n\\usepackage{graphicx}\n\\pgfplotsset{compat=1.16}\n"
            + style
            + "\n\\newcommand{\\sfigdir}{figures/surface}\n\\begin{document}\n\\input{figures/surface/"
            + n
            + ".tex}\n\\end{document}\n"
        )
        r = subprocess.run(
            [
                "pdflatex",
                "-interaction=nonstopmode",
                "-halt-on-error",
                f"-output-directory={out}",
                str(wrap),
            ],
            cwd=ms,
            capture_output=True,
            text=True,
        )
        if r.returncode != 0:
            raise RuntimeError(
                n + ": " + "\n".join(x for x in r.stdout.splitlines() if x.startswith("!"))[:900]
            )
        info = subprocess.run(
            ["pdfinfo", str(out / f"{n}_check.pdf")], capture_output=True, text=True
        ).stdout
        wpt = float([x for x in info.splitlines() if x.startswith("Page size")][0].split()[2])
        print(f"{n}: {wpt - 8:.0f} pt content width (text width 390 pt)")
        subprocess.run(
            [
                "pdftoppm",
                "-png",
                "-r",
                "150",
                "-singlefile",
                str(out / f"{n}_check.pdf"),
                str(out / f"{n}_preview"),
            ],
            check=True,
        )
        for ext in ("aux", "log", "tex"):
            (out / f"{n}_check.{ext}").unlink(missing_ok=True)


def main(manuscript: str) -> None:
    ms = Path(manuscript).resolve()
    d = ms / "figures" / "surface"
    d.mkdir(parents=True, exist_ok=True)
    S = json.loads((SRC / "summary.json").read_text())
    for p in SRC.glob("*.png"):
        shutil.copy(p, d / p.name)
    figs = {
        "fig_surface_compact": compact(S),
        "fig_surface_rgb": rgb_fig(S),
        "fig_surface_gate": gate_fig(S),
        "fig_surface_normals": normals_fig(S),
    }
    for n, t in figs.items():
        (d / f"{n}.tex").write_text(t)
    (d / "tab_surface.tex").write_text(table(S))
    if shutil.which("pdflatex"):
        compile_check(ms, list(figs), SRC / "check")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else str(ROOT / "manuscript"))
