"""CPU toy follow-ups: (1) miscalibrated posterior, (2) large-area faults. Writes docs/toy-followups.md.

Usage: python scripts/toy_followups.py [--g 16] [--n0 150] [--n1 60] [--workers 6]
"""
from __future__ import annotations

import argparse
import sys
import time
from multiprocessing import Pool
from pathlib import Path

import numpy as np
from scipy.stats import chi2

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
from dcal.stat import empirical_threshold, fault_statistic  # noqa: E402
from dcal.toy import ToyConfig, World  # noqa: E402

VARIANTS = ["oracle", "kernel", "kernel_nr"]
W = {}


def init(g, miscal):
    W["w"] = World(ToyConfig(g=g, miscal=miscal), 0)


def one(args):
    fault, kappa, area, seed = args
    w = W["w"]
    S, D, Kr, Ku, _ = w.simulate(np.random.default_rng(seed), fault, kappa, area)
    m2 = w.cfg.miscal ** 2
    return {"oracle": fault_statistic(S, D, Kr, Sigma_u=m2 * Ku)["T"],      # covariance the model would report
            "kernel": fault_statistic(S, D, Kr, grid_shape=w.shape, cov="kernel")["T"],
            "kernel_nr": fault_statistic(S, D, Kr, grid_shape=w.shape, cov="kernel", robust=False)["T"]}


def run(pool, fault, kappa, area, n, base):
    res = pool.map(one, [(fault, kappa, area, base + i) for i in range(n)], chunksize=4)
    return {v: np.array([r[v] for r in res]) for v in VARIANTS}


def mdf(curve):
    ks = sorted(curve)
    p = [curve[k] for k in ks]
    for i, pi in enumerate(p):
        if pi >= 0.8:
            if i == 0:
                return f"<={ks[0]}"
            k0, k1, p0, p1 = ks[i - 1], ks[i], p[i - 1], pi
            return f"{k0 + (0.8 - p0) * (k1 - k0) / max(p1 - p0, 1e-9):.2f}"
    return f">{ks[-1]}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--g", type=int, default=16)
    ap.add_argument("--n0", type=int, default=150)
    ap.add_argument("--n1", type=int, default=60)
    ap.add_argument("--workers", type=int, default=6)
    ap.add_argument("--out", default=str(Path(__file__).resolve().parents[1] / "docs" / "toy-followups.md"))
    a = ap.parse_args()
    t0 = time.time()
    n = a.g ** 2
    chi_thr = chi2.ppf(0.95, n - 2)
    kappas = [0.5, 1.0, 1.5, 2.5, 4.0]
    L = ["# Toy follow-ups (CPU, synthetic Gaussian toy)\n",
         f"Generated by `scripts/toy_followups.py`; grid {a.g}x{a.g} (n={n}), M=10, {a.n0} clean trials and {a.n1} per cell, alpha=0.05, "
         "empirical-null threshold of the same pipeline. One seed; power carries about +-0.06. `oracle` = covariance the model would report "
         "(miscal^2 x true), (s,t) fitted robustly; `kernel` = stationary kernel estimated from the samples, robust fit; `kernel_nr` = same, plain fit.\n"]
    L.append("## 1. Miscalibrated posterior: sample spread = miscal x the truth's posterior spread\n")
    L.append("miscal < 1 is an over-confident model, > 1 under-confident. The truth and the render do not change.\n")
    L.append(f"| miscal | variant | mean T/(n-2) | false-alarm at chi2 95% ({chi_thr:.0f}) | MDF square | MDF warp |\n|---|---|---|---|---|---|")
    for mc in [0.6, 1.0, 1.6]:
        with Pool(a.workers, initializer=init, initargs=(a.g, mc)) as pool:
            null = run(pool, None, 0.0, 0.0, a.n0, 10_000)
            thr = {v: empirical_threshold(null[v], 0.05) for v in VARIANTS}
            m = {}
            for fault in ["square", "warp"]:
                cur = {v: {} for v in VARIANTS}
                for k in kappas:
                    r = run(pool, fault, k, 0.12, a.n1, 20_000)
                    for v in VARIANTS:
                        cur[v][k] = float((r[v] > thr[v]).mean())
                m[fault] = {v: mdf(cur[v]) for v in VARIANTS}
        for v in VARIANTS:
            L.append(f"| {mc} | {v} | {null[v].mean() / (n - 2):.2f} | {(null[v] > chi_thr).mean():.2f} | {m['square'][v]} | {m['warp'][v]} |")
    L.append("\n## 2. Large-area faults (left band covering exactly `area` of the view; kappa fixed), power vs area fraction\n")
    with Pool(a.workers, initializer=init, initargs=(a.g, 1.0)) as pool:
        null = run(pool, None, 0.0, 0.0, a.n0, 10_000)
        thr = {v: empirical_threshold(null[v], 0.05) for v in VARIANTS}
        for kappa in [2.5, 4.0]:
            L.append(f"\nkappa = {kappa}\n")
            L.append("| area | " + " | ".join(VARIANTS) + " |\n|---|" + "---|" * len(VARIANTS))
            for area in [0.05, 0.15, 0.30, 0.50, 0.70, 0.85, 0.95]:
                r = run(pool, "band", kappa, area, a.n1, 30_000)
                L.append(f"| {area} | " + " | ".join(f"{(r[v] > thr[v]).mean():.2f}" for v in VARIANTS) + " |")
    L.append(f"\n({time.time() - t0:.0f} s)")
    Path(a.out).write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
