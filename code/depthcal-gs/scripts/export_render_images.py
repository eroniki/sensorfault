"""Write the individual render images (no axes, no text) used inside the TikZ panels, from the SAVED surfels. GPU; never trains.

Per case (heldout 2/6/10, and view-6 guard cases poisoned/leaky): <case>_in.png, _rgb.png, _depth.png, _gt.png, _err.png in
figures/tikz/img/, depth colourised with viridis and errors with magma on shared scales (grey = no value), plus
figures/tikz/data/pipes_render_stats.csv with the numbers and the scales (the colourbars are drawn by PGFPlots from those scales).
Usage: python scripts/export_render_images.py /path/to/eth3d/pipes/pipes [--surfels DIR]
"""
from __future__ import annotations

import argparse
import csv
import sys
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import numpy as np  # noqa: E402
from matplotlib import colormaps  # noqa: E402
from PIL import Image  # noqa: E402
from scipy.ndimage import maximum_filter  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT / "scripts"))
from dcal.eth3d import load_scene  # noqa: E402
from dcal.surface import ViewData  # noqa: E402
from render_pipes_panels import ERR_MAX, dilate_nan, load_params, metrics  # noqa: E402

GREY = np.array([217, 217, 217], np.uint8)


def colourise(a, cmap, vmin, vmax):
    out = np.empty(a.shape + (3,), np.uint8)
    ok = np.isfinite(a)
    t = np.clip((np.where(ok, a, vmin) - vmin) / (vmax - vmin), 0, 1)
    out[:] = (colormaps[cmap](t)[..., :3] * 255).astype(np.uint8)
    out[~ok] = GREY
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("scene_dir")
    ap.add_argument("--surfels", default=str(Path.home() / "datasets" / "eth3d" / "pipes" / "surfels"))
    a = ap.parse_args()
    base = Path(a.scene_dir)
    ev = load_scene(base.parent, base.name, scale=8.0)
    views = {v.view_id: ViewData(v.view_id, v.rgb, v.gt_depth, v.K, v.T_cw) for v in ev}
    allgt = np.concatenate([v.depth[np.isfinite(v.depth)] for v in views.values()])
    dmin, dmax = float(np.percentile(allgt, 1)), float(np.percentile(allgt, 99))
    img = ROOT / "figures" / "tikz" / "img"
    img.mkdir(parents=True, exist_ok=True)
    rows = []
    cases = [(f"view{j}", j, f"j{j}_heldout_2000.pt") for j in (2, 6, 10)] + [("guard_poisoned", 6, "j6_poisoned_2000.pt"), ("guard_leaky", 6, "j6_leaky_2000.pt")]
    for name, j, fn in cases:
        P = load_params(Path(a.surfels) / fn)
        m, rgb, d, al = metrics(P, views[j])
        gt = np.asarray(views[j].depth)
        valid = np.isfinite(gt)
        show = al > 0.5
        err = np.where(valid & show, np.abs(d - gt), np.nan)
        Image.fromarray((np.clip(views[j].rgb, 0, 1) * 255).astype(np.uint8)).save(img / f"{name}_in.png")
        Image.fromarray((np.clip(rgb, 0, 1) * 255).astype(np.uint8)).save(img / f"{name}_rgb.png")
        Image.fromarray(colourise(np.where(show, d, np.nan), "viridis", dmin, dmax)).save(img / f"{name}_depth.png")
        Image.fromarray(colourise(dilate_nan(np.where(valid, gt, np.nan)), "viridis", dmin, dmax)).save(img / f"{name}_gt.png")
        Image.fromarray(colourise(dilate_nan(err), "magma", 0, ERR_MAX)).save(img / f"{name}_err.png")
        rows.append([name, j, round(100 * valid.mean(), 1), round(100 * show.mean(), 1), m["coverage_of_valid_gt"], m["rel_err_median"], m["rel_err_p90"],
                     m["psnr_db"], round(dmin, 3), round(dmax, 3), ERR_MAX])
        print(name, m, flush=True)
    with open(ROOT / "figures" / "tikz" / "data" / "pipes_render_stats.csv", "w", newline="") as f:
        c = csv.writer(f)
        c.writerow(["case", "view", "gt_valid_pct", "render_alpha_pct", "cov", "med_rel", "p90_rel", "psnr", "dmin", "dmax", "errmax"])
        c.writerows(rows)
    with open(ROOT / "figures" / "tikz" / "data" / "pipes_render_macros.tex", "w") as f:
        f.write("% generated by scripts/export_render_images.py: numbers printed on the pipes render panels\n")
        for r in rows:
            for key, val in zip(("view", "validpct", "alphapct", "cov", "med", "p90", "psnr", "dmin", "dmax", "errmax"), r[1:]):
                f.write(f"\\expandafter\\def\\csname Px@{r[0]}@{key}\\endcsname{{{val}}}%\n")
            for key, val in (("covpct", f"{100 * r[4]:.1f}"), ("medpct", f"{100 * r[5]:.2f}"), ("p90pct", f"{100 * r[6]:.2f}")):
                f.write(f"\\expandafter\\def\\csname Px@{r[0]}@{key}\\endcsname{{{val}}}%\n")


if __name__ == "__main__":
    main()
