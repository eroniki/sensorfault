"""TikZ/PGFPlots figures and table for the MatrixCity block 3 2DGS RGB model (style: figstyle.tex).

Reads results/rgb (from rgb_train_2dgs.py and rgb_render_view.py): rendered and ground-truth PNGs for the
Figure S5 example views (training frames 88, 59, 58) and test frames 0 and 22, the per-pixel absolute error, and metrics.json.
Writes fig_rgb_views.tex (ground truth | render | |error| per view), fig_rgb_test.tex (per-view test
PSNR and SSIM), tab_rgb.tex, standalone PDFs and preview PNGs.
Run: python3 experiments/rgb_figures.py results/rgb
"""

from __future__ import annotations

import json
import shutil
import subprocess
import sys
from pathlib import Path

import numpy as np
from PIL import Image

HERE = Path(__file__).resolve().parent
VIRIDIS = np.array(
    [(68, 1, 84), (59, 82, 139), (33, 145, 140), (94, 201, 98), (253, 231, 37)], float
)
ERR_MAX = 0.25  # |error| colour range, mean over RGB channels in [0, 1]
PW = 3.7  # panel width [cm]
TEST_ROWS = (0, 22)  # test frames shown: near best (28.2 dB) and worst (16.7 dB)
PH = PW * 540 / 960


def viridis(x: np.ndarray) -> np.ndarray:
    t = np.clip(x, 0, 1) * (len(VIRIDIS) - 1)
    i = np.minimum(t.astype(int), len(VIRIDIS) - 2)
    f = (t - i)[..., None]
    return ((1 - f) * VIRIDIS[i] + f * VIRIDIS[i + 1]).astype(np.uint8)


def err_png(render: Path, gt: Path, out: Path) -> float:
    a = np.asarray(Image.open(render).convert("RGB"), float) / 255
    b = np.asarray(Image.open(gt).convert("RGB"), float) / 255
    e = np.abs(a - b).mean(-1)
    Image.fromarray(viridis(e / ERR_MAX)).save(out)
    return float(e.mean())


def views_fig(rows: list[tuple[str, str]]) -> str:
    """rows: (file prefix, row label)."""
    body = []
    titles = ["Ground truth", "2DGS render", "Absolute error"]
    for ri, (tag, lab) in enumerate(rows):
        for ci, kind in enumerate(["gt", "render", "err"]):
            opts = []
            if ri == 0:
                opts.append(f"title={{{titles[ci]}}}")
            if ci == 0:
                opts.append(f"ylabel={{{lab}}}")
            body.append(
                rf"\nextgroupplot[{', '.join(opts)}]"
                + "\n"
                + rf"\addplot graphics[xmin=0, xmax=1, ymin=0, ymax=1] {{\rfigdir/{tag}_{kind}.png}};"
            )
    n = len(rows)
    return rf"""% MatrixCity block 3, 2DGS RGB renders (generated by experiments/rgb_figures.py)
\begin{{tikzpicture}}
\begin{{groupplot}}[sfimage, group style={{group size=3 by {n}, horizontal sep=0.12cm, vertical sep=0.12cm}},
  width={PW}cm, height={PH:.3f}cm, xmin=0, xmax=1, ymin=0, ymax=1,
  ylabel style={{align=center, font=\sffamily\tiny}}, title style={{font=\sffamily\scriptsize, yshift=-2pt}}]
{chr(10).join(body)}
\end{{groupplot}}
\begin{{axis}}[sfcolorbar={PW}cm, colormap name=sfviridis, at={{($(group c3r{n}.south)+(0,-0.12cm)$)}},
  anchor=north, point meta min=0, point meta max={ERR_MAX}, colorbar style={{xlabel={{Mean absolute RGB error ($\geq${ERR_MAX} clipped)}}}}]
\addplot[draw=none] coordinates {{(0,0)}};
\end{{axis}}
\end{{tikzpicture}}
"""


def test_fig(m: dict) -> str:
    pv = m["test"]["per_view"]
    ps = " ".join(f"({i},{v['psnr']:.3f})" for i, v in enumerate(pv))
    ss = " ".join(f"({i},{v['ssim']:.4f})" for i, v in enumerate(pv))
    ticks = ",".join(str(i) for i in range(len(pv)))
    labels = ",".join(str(v["frame"]) for v in pv)
    mp, ms = m["test"]["psnr_mean"], m["test"]["ssim_mean"]
    common = (
        rf"sfaxis, width=5.6cm, height=3.0cm, scale only axis, xmin=-0.7, xmax={len(pv) - 0.3}, xtick={{{ticks}}}, "
        rf"xticklabels={{{labels}}}, xticklabel style={{rotate=90, font=\sffamily\sansmath\tiny}}, xlabel={{Test frame}}"
    )
    return rf"""% MatrixCity block 3, 2DGS test-split metrics (generated by experiments/rgb_figures.py)
\begin{{tikzpicture}}
\begin{{groupplot}}[group style={{group size=2 by 1, horizontal sep=1.3cm}}]
\nextgroupplot[{common}, ylabel={{PSNR [dB]}}, ymin=0, ymax={1.3 * max(v["psnr"] for v in pv):.1f}, title={{\sfsub{{a}}}}, legend style={{at={{(0.02,0.97)}}, anchor=north west}}]
\addplot[sfbar, sfbarred, forget plot] coordinates {{{ps}}};
\addplot[black, dashed, line width=0.7pt, domain=-0.7:{len(pv) - 0.3}, samples=2] {{{mp:.3f}}};
\legend{{Mean {mp:.2f} dB}}
\nextgroupplot[{common}, ylabel={{SSIM}}, ymin=0, ymax=1.25, ytick={{0,0.2,0.4,0.6,0.8,1}}, title={{\sfsub{{b}}}}, legend style={{at={{(0.02,0.97)}}, anchor=north west}}]
\addplot[sfbar, sfbarred, forget plot] coordinates {{{ss}}};
\addplot[black, dashed, line width=0.7pt, domain=-0.7:{len(pv) - 0.3}, samples=2] {{{ms:.4f}}};
\legend{{Mean {ms:.3f}}}
\end{{groupplot}}
\end{{tikzpicture}}
"""


def table(m: dict) -> str:
    t, f = m["test"], m["figure_train_views"]
    rows = [
        rf"Test split ({t['n']} views) & {t['psnr_mean']:.2f} $\pm$ {t['psnr_sd']:.2f} & {t['ssim_mean']:.3f} $\pm$ {t['ssim_sd']:.3f} \\"
    ]
    names = {
        "88": "View 69 (frame 88; clean in E1), train",
        "59": "View 59 (frame 59; faulty in E1), train",
        "58": "View 58 (frame 58; swamped in E1), train",
    }
    for k, lab in names.items():
        if k in f:
            rows.append(rf"{lab} & {f[k]['psnr']:.2f} & {f[k]['ssim']:.3f} \\")
    return (
        "% generated by experiments/rgb_figures.py\n\\begin{tabular}{lcc}\n\\toprule\nViews & PSNR [dB] & SSIM \\\\\n\\midrule\n"
        + "\n".join(rows)
        + "\n\\bottomrule\n\\end{tabular}\n"
    )


def compile_pdf(d: Path, name: str) -> None:
    if not shutil.which("pdflatex"):
        return
    wrap = d / f"_sa_{name}.tex"
    wrap.write_text(
        "\\documentclass[border=4pt]{standalone}\n\\usepackage{pgfplots}\n\\usepgfplotslibrary{groupplots}\n"
        "\\usetikzlibrary{calc}\n\\usepackage{sansmath}\n\\pgfplotsset{compat=1.16}\n"
        + (HERE / "figstyle.tex").read_text()
        + "\n\\newcommand{\\rfigdir}{.}\n\\begin{document}\n\\input{"
        + name
        + ".tex}\n\\end{document}\n"
    )
    r = subprocess.run(
        ["pdflatex", "-interaction=nonstopmode", "-halt-on-error", wrap.name],
        cwd=d,
        capture_output=True,
        text=True,
    )
    if r.returncode != 0:
        raise RuntimeError(
            name + ": " + "\n".join(x for x in r.stdout.splitlines() if x.startswith("!"))[:600]
        )
    (d / f"{wrap.stem}.pdf").rename(d / f"{name}.pdf")
    for ext in ("aux", "log", "tex"):
        (d / f"{wrap.stem}.{ext}").unlink(missing_ok=True)
    if shutil.which("pdftoppm"):
        subprocess.run(
            ["pdftoppm", "-png", "-r", "250", "-singlefile", f"{name}.pdf", f"{name}_preview"],
            cwd=d,
            check=True,
        )


def main(root: str) -> None:
    d = Path(root)
    m = json.loads((d / "metrics.json").read_text())
    rows = [
        ("train_0088", "Clean in E1\\\\view 69 (train)"),
        ("train_0059", "Faulty in E1\\\\view 59 (train)"),
        ("train_0058", "Swamped in E1\\\\view 58 (train)"),
    ]
    pv = {v["frame"]: v for v in m["test"]["per_view"]}
    for fr in (
        TEST_ROWS
    ):  # a well-reconstructed and the worst held-out view (render with rgb_render_view.py)
        rows.append((f"test_{fr:04d}", f"Held-out frame {fr}\\\\(test, {pv[fr]['psnr']:.1f} dB)"))
    for tag, _ in rows:
        err_png(d / f"{tag}_render.png", d / f"{tag}_gt.png", d / f"{tag}_err.png")
    (d / "fig_rgb_views.tex").write_text(views_fig(rows))
    (d / "fig_rgb_test.tex").write_text(test_fig(m))
    (d / "tab_rgb.tex").write_text(table(m))
    for n in ("fig_rgb_views", "fig_rgb_test"):
        compile_pdf(d, n)
    print("ok")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "results/rgb")
