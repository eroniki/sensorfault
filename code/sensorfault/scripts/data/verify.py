#!/usr/bin/env python3
"""Check the expected on-disk layout of each dataset under $SENSORFAULT_DATA.

No network. Exit code 0 unless --strict and a required dataset is missing.
Usage: python3 -I scripts/data/verify.py [--root DIR] [--strict] [--scenes dragon skate]
"""
from __future__ import annotations

import argparse
import os
import sys
from pathlib import Path

SK_CAMS_DEPTH = ["kinect_v2", "phone_right", "phone_left", "real_sense"]


def nonempty(p: Path) -> bool:
    return p.is_dir() and any(p.iterdir())


def check_skoltech(root: Path, scenes: list[str]) -> tuple[str, str]:
    base = root / "skoltech3d"
    if not base.is_dir():
        return "MISSING", "no skoltech3d/ directory"
    miss = []
    cal = base / "dataset" / "calibration"
    for cam in SK_CAMS_DEPTH:
        if not nonempty(cal / cam):
            miss.append(f"calibration/{cam}")
    present = sorted(p.name for p in (base / "dataset").iterdir() if p.is_dir() and p.name != "calibration") \
        if (base / "dataset").is_dir() else []
    use = scenes or present
    if not use:
        miss.append("no scene directories")
    for s in use:
        sd = base / "dataset" / s
        if not (sd / "stl" / "reconstruction" / "cleaned.ply").is_file():
            miss.append(f"{s}/stl/reconstruction/cleaned.ply")
        for cam in SK_CAMS_DEPTH:
            if not nonempty(sd / cam / "depth" / "undistorted") and not nonempty(sd / cam / "depth"):
                miss.append(f"{s}/{cam}/depth")
    return ("OK", f"{len(use)} scene(s)") if not miss else ("INCOMPLETE", "; ".join(miss[:6]) + (" ..." if len(miss) > 6 else ""))


def check_replica(root: Path, _s) -> tuple[str, str]:
    base = root / "replica"
    if not base.is_dir():
        return "MISSING", "no replica/ directory"
    scenes = [p for p in base.iterdir() if p.is_dir() and not p.name.startswith("_") and (p / "mesh.ply").is_file()]
    return ("OK", f"{len(scenes)} scene(s) with mesh.ply") if scenes else ("INCOMPLETE", "no <scene>/mesh.ply found")


def check_rendered(root: Path, _s) -> tuple[str, str]:
    base = root / "replica_rendered"
    if not base.is_dir():
        return "MISSING", "no replica_rendered/ (generated by render_replica_multisensor.py)"
    ms = list(base.glob("*/*/manifest.json"))
    return ("OK", f"{len(ms)} rendering(s)") if ms else ("INCOMPLETE", "no */*/manifest.json")


def check_nonempty(name: str):
    def f(root: Path, _s) -> tuple[str, str]:
        p = root / name
        if not p.is_dir():
            return "MISSING", f"no {name}/"
        return ("OK", "non-empty") if nonempty(p) else ("INCOMPLETE", "empty")
    return f


DATASETS = [
    ("skoltech3d", True, check_skoltech),
    ("replica", True, check_replica),
    ("replica_rendered", False, check_rendered),
    ("us3d_dfc2019", False, check_nonempty("us3d_dfc2019")),
    ("mvs3dm_san_fernando", False, check_nonempty("mvs3dm_san_fernando")),
]


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--root", default=os.environ.get("SENSORFAULT_DATA", "./data"))
    ap.add_argument("--scenes", nargs="*", default=[], help="Skoltech3D scenes to require (default: whatever is present)")
    ap.add_argument("--strict", action="store_true", help="exit 1 if a required dataset is not OK")
    a = ap.parse_args()
    root = Path(a.root).resolve()
    print(f"root: {root}\n")
    print(f"{'dataset':22s} {'required':9s} {'status':11s} detail")
    bad = False
    for name, req, fn in DATASETS:
        st, detail = fn(root, a.scenes)
        print(f"{name:22s} {'yes' if req else 'optional':9s} {st:11s} {detail}")
        bad |= req and st != "OK"
    return 1 if (a.strict and bad) else 0


if __name__ == "__main__":
    sys.exit(main())
